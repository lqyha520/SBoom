test('工作台账号、访客和两个游戏各自保存；返回工作台恢复草稿', async ({ page, context }) => {
  await context.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname
    let json: unknown
    if (path === '/api/v1/auth/me') json = { id: 7, username: 'teacher', role: 'user' }
    else if (path === '/api/v1/scope/available') json = { available: { 小学三年级: ['数学'] } }
    else if (path === '/api/v1/scope') json = { allowed: ['加减法'] }
    else if (path === '/api/v1/me/templates') json = { templates: [] }
    else if (path === '/api/v1/me/usage') json = { requests: 0, daily_limit: 0 }
    else throw new Error('未声明的请求：' + path)
    await route.fulfill({ json })
  })
  await page.goto('/')
  const title = page.getByRole('textbox', { name: '试卷标题', exact: true })
  await title.fill('机器人探索前的草稿')
  await page.getByRole('button', { name: '学习游戏', exact: true }).click()
  await expect(page.getByRole('heading', { name: '小小店长.' })).toBeVisible()
  await page.getByRole('link', { name: '机器人闯迷宫', exact: true }).click()
  await expect(firstHeading(page)).toBeVisible()
  await add(page, '前进')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('lc_u7_game_robot_maze_v1')!).program)).toEqual([{ type: 'forward' }])
  expect(await page.evaluate(k => localStorage.getItem(k), key)).toBeNull()
  await page.getByRole('link', { name: '返回工作台', exact: true }).click()
  await expect(title).toHaveValue('机器人探索前的草稿')
  await page.getByRole('button', { name: '学习游戏', exact: true }).click()
  await expect(page.getByRole('heading', { name: '小小店长.' })).toBeVisible()
  await page.getByRole('link', { name: '机器人闯迷宫', exact: true }).click()
  await expect(firstHeading(page)).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('lc_u7_game_robot_maze_v1')!).program)).toHaveLength(1)
})
