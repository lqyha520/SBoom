import { expect, test, type Page } from '@playwright/test'

const key = 'lc_game_robot_maze_v1_guest'
const firstHeading = (page: Page) => page.getByRole('heading', { name: '第一次出发', exact: true })
async function add(page: Page, ...commands: string[]) {
  for (const command of commands) await page.getByRole('button', { name: `添加${command}指令`, exact: true }).click()
}
async function getSave(page: Page) { return page.evaluate(k => JSON.parse(localStorage.getItem(k)!), key) }
async function run(page: Page) {
  const fast = page.getByRole('checkbox', { name: '快速运行', exact: true })
  await fast.check()
  await page.getByRole('button', { name: '运行程序', exact: true }).click()
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function currentLevelFits(page: Page) {
  return page.evaluate(() => {
    const journey = document.querySelector('.journey')
    const current = journey?.querySelector('.level-button.current')
    if (!journey || !current) return false
    const view = journey.getBoundingClientRect()
    const card = current.getBoundingClientRect()
    return card.left >= view.left - 1 && card.right <= view.right + 1
  })
}

test('免登录游戏：编排、单步、暂停、刷新恢复、通关解锁与游戏切换', async ({ page }, info) => {
  const errors: string[] = []
  const requests: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.url().includes('/api/')) requests.push(r.url()) })
  await page.goto('/#/games/robot-maze')
  await expect(firstHeading(page)).toBeVisible()
  await page.screenshot({ path: info.outputPath('robot-maze-desktop.png'), fullPage: true })
  await noOverflow(page)
  await page.getByRole('button', { name: '运行程序', exact: true }).click()
  await expect(page.getByRole('status', { name: '机器人反馈' })).toContainText('先点击')
  await add(page, '前进', '前进')
  await page.reload()
  await expect(firstHeading(page)).toBeVisible()
  expect((await getSave(page)).program).toHaveLength(2)
  await page.getByRole('button', { name: '单步', exact: true }).click()
  await expect(page.getByRole('img', { name: /迷宫地图/ })).toHaveAttribute('aria-label', /第2列/)
  await expect(page.getByRole('button', { name: '添加前进指令' })).toBeDisabled()
  await page.getByRole('button', { name: '继续运行', exact: true }).click()
  await page.getByRole('button', { name: '暂停运行', exact: true }).click()
  await page.getByRole('button', { name: '回到起点', exact: true }).click()
  await add(page, '前进', '前进')
  await run(page)
  await expect(page.getByText('任务完成，干得漂亮！', { exact: true })).toBeVisible()
  expect((await getSave(page)).stars[0]).toBe(3)
  await page.getByRole('button', { name: '前往下一关', exact: true }).click()
  await expect(page.getByRole('heading', { name: '沿途的礼物', exact: true })).toBeVisible()
  expect((await getSave(page)).program).toEqual([])
  await page.reload()
  await expect(page.getByRole('heading', { name: '沿途的礼物', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '小小店长', exact: true }).click()
  await expect(page.getByRole('heading', { name: '小小店长.' })).toBeVisible()
  await page.getByRole('button', { name: '装入一个苹果', exact: true }).click()
  await page.getByRole('link', { name: '机器人闯迷宫', exact: true }).click()
  await expect(page.getByRole('heading', { name: '沿途的礼物', exact: true })).toBeVisible()
  expect((await getSave(page)).stars[0]).toBe(3)
  await page.getByRole('link', { name: '小小店长', exact: true }).click()
  await expect(page.getByRole('heading', { name: '小小店长.' })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('lc_game_little_shop_v1_guest')!).bag.apple)).toBe(1)
  expect(errors).toEqual([]); expect(requests).toEqual([])
})

