test('待付款单减少后自动恢复有效页码，仍可选择剩余结算单', async ({ page, context }) => {
  const server = await businessFixture(context)
  for (let i = 0; i < 20; i++) server.statements.push({ ...server.statements[0]!, id: 'pending-' + i })
  await context.route('**/api/v1/admin/settlements/payout-candidates?**', route => {
    const current = Math.min(Number(new URL(route.request().url()).searchParams.get('page') || 1), Math.max(1, Math.ceil(server.statements.length / 20)))
    const offset = (current - 1) * 20
    return route.fulfill({ json: { items: server.statements.slice(offset, offset + 20).map(item => ({ ...item, payout_issues: [] })), total: server.statements.length, page: current } })
  })
  await page.goto('/admin/#financePayments?available=2')
  await page.getByText('选择待付款结算单，创建批次', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '加入付款批次pending-19', exact: true })).toBeVisible()
  server.statements.splice(1)
  await page.getByRole('button', { name: '刷新付款批次', exact: true }).click()
  await expect(page).not.toHaveURL(/available=2/)
  await expect(page.getByRole('checkbox', { name: '加入付款批次statement-business-1', exact: true })).toBeVisible()
})

