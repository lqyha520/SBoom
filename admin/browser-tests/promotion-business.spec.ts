  await expect(page.getByRole('button', { name: '确认登记匹配回单' })).toHaveCount(0)
  expect(server.writes.some(item => item.path.endsWith('/import'))).toBe(false)
  await page.getByRole('button', { name: '预览回单匹配' }).click()
  await page.getByRole('checkbox', { name: /已核对回单，仅登记匹配通过/ }).check()
  await page.getByRole('button', { name: '确认登记匹配回单' }).click()
  await expect(page.getByText(/回单登记：成功 1 条/)).toBeVisible()
  expect(server.writes.filter(item => item.path.endsWith('/import'))).toHaveLength(1)
